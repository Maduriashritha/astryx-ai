'use client'

import { useState } from 'react'
import useSWR from 'swr'
import type { GenerateResult, Generation } from '@/lib/types'
import { ActivityFeed } from './activity-feed'
import { Header } from './header'
import { OutputCard } from './output-card'
import { PromptInput } from './prompt-input'
import { Sidebar } from './sidebar'

type HistoryResponse = { generations: Generation[]; configured: boolean }

const fetcher = (url: string) => fetch(url).then((r) => r.json() as Promise<HistoryResponse>)

export function Dashboard() {
  const { data, isLoading: historyLoading, mutate } = useSWR('/api/generations', fetcher, {
    revalidateOnFocus: false,
  })
  const [current, setCurrent] = useState<Generation | null>(null)
  const [saved, setSaved] = useState<boolean | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [isGenerating, setIsGenerating] = useState(false)

  async function handleGenerate(prompt: string) {
    setIsGenerating(true)
    setError(null)
    try {
      const res = await fetch('/api/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ prompt }),
      })
      const json = await res.json()
      if (!res.ok) {
        setError(json.error ?? 'Something went wrong.')
        return false
      }
      const result = json as GenerateResult
      setCurrent(result.generation)
      setSaved(result.saved)
      mutate(
        (prev) => ({
          configured: prev?.configured ?? false,
          generations: [result.generation, ...(prev?.generations ?? [])],
        }),
        { revalidate: false },
      )
      return true
    } catch {
      setError('Network error. Please check your connection and try again.')
      return false
    } finally {
      setIsGenerating(false)
    }
  }

  return (
    <div className="flex h-dvh overflow-hidden">
      <Sidebar />
      <div className="flex min-w-0 flex-1 flex-col">
        <Header />
        <div className="flex min-h-0 flex-1 flex-col overflow-y-auto lg:flex-row lg:overflow-hidden">
          <main className="flex min-w-0 flex-1 flex-col gap-5 p-4 md:p-6 lg:overflow-y-auto">
            <div>
              <h2 className="text-xl font-semibold tracking-tight text-balance">What would you like to create?</h2>
              <p className="mt-1 text-sm text-muted-foreground">
                Responses are generated by llama-3.3-70b-versatile via Groq.
              </p>
            </div>
            <PromptInput onSubmit={handleGenerate} isLoading={isGenerating} />
            <OutputCard generation={current} isLoading={isGenerating} error={error} saved={saved} />
          </main>
          <ActivityFeed
            items={data?.generations ?? []}
            isLoading={historyLoading}
            configured={data?.configured ?? true}
            activeId={current?.id ?? null}
            onSelect={(g) => {
              setCurrent(g)
              setSaved(null)
              setError(null)
            }}
          />
        </div>
      </div>
    </div>
  )
}
